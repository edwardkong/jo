// Generates two obviously-fake "photos" into src/assets/uploads/ so the layout can
// be judged with real image dimensions before she has taken any. They are flat
// warm colours with a simple drawn shape and the words "placeholder photo" on them,
// so nobody mistakes them for the real thing.
//
// Run:   node scripts/make-placeholders.mjs
// Each file is checked to be under 200 KB (the script fails loudly if not).

import sharp from 'sharp';
import { mkdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WIDTH = 1600;
const HEIGHT = 1200;
const MAX_BYTES = 200 * 1024;

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/assets/uploads');

/**
 * @typedef {object} Placeholder
 * @property {string} file    output filename (lowercase extension, like the CMS enforces)
 * @property {string} paper   flat background colour
 * @property {string} ink     line colour, shared by the drawing and the caption
 * @property {string} drawing SVG fragment placed on a 1600x1200 canvas
 * @property {string} caption second line under "placeholder photo"
 */

/** A loaf with three score marks on a board. */
function loaf(ink) {
  return `
    <ellipse cx="800" cy="790" rx="560" ry="110" fill="${ink}" fill-opacity="0.12"/>
    <path d="M380 720 Q380 420 800 400 Q1220 420 1220 720 Q1220 800 1140 800 L460 800 Q380 800 380 720 Z"
          fill="#d59a55" stroke="${ink}" stroke-width="7" stroke-linejoin="round"/>
    <g stroke="${ink}" stroke-width="9" stroke-linecap="round" stroke-opacity="0.75" fill="none">
      <path d="M560 560 l130 -80"/>
      <path d="M740 535 l130 -80"/>
      <path d="M920 535 l130 -80"/>
    </g>`;
}

/** A plate with a bun on it and a few crumbs. */
function plate(ink) {
  return `
    <ellipse cx="800" cy="600" rx="560" ry="300" fill="#f6ecd8" stroke="${ink}" stroke-width="7"/>
    <ellipse cx="800" cy="600" rx="440" ry="225" fill="none" stroke="${ink}" stroke-width="4" stroke-opacity="0.45"/>
    <circle cx="800" cy="560" r="140" fill="#dda86c" stroke="${ink}" stroke-width="7"/>
    <path d="M740 505 Q790 450 860 505" fill="none" stroke="${ink}" stroke-width="6" stroke-linecap="round" stroke-opacity="0.6"/>
    <g fill="${ink}" fill-opacity="0.5">
      <circle cx="1000" cy="690" r="9"/><circle cx="1040" cy="720" r="6"/>
      <circle cx="580" cy="700" r="7"/><circle cx="620" cy="730" r="5"/>
    </g>`;
}

/** @type {Placeholder[]} */
const placeholders = [
  {
    file: 'placeholder-lemon-loaf.jpg',
    paper: '#ead9b7',
    ink: '#7a4f2a',
    drawing: loaf('#7a4f2a'),
    caption: 'a loaf, roughly · generated by scripts/make-placeholders.mjs',
  },
  {
    file: 'placeholder-plate.jpg',
    paper: '#d9c39c',
    ink: '#6b4526',
    drawing: plate('#6b4526'),
    caption: 'a plate, roughly · generated by scripts/make-placeholders.mjs',
  },
];

/** Builds the full SVG overlay: drawing plus the two caption lines. */
function overlay(p) {
  const font = 'Helvetica, Arial, sans-serif';
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}">
    ${p.drawing}
    <text x="800" y="1040" text-anchor="middle" font-family="${font}" font-size="64" font-weight="bold" fill="${p.ink}">placeholder photo</text>
    <text x="800" y="1100" text-anchor="middle" font-family="${font}" font-size="30" fill="${p.ink}" fill-opacity="0.8">${p.caption}</text>
    <text x="40" y="70" font-family="${font}" font-size="28" fill="${p.ink}" fill-opacity="0.6">placeholder photo</text>
  </svg>`;
}

async function make(p) {
  const target = path.join(outDir, p.file);
  await sharp({ create: { width: WIDTH, height: HEIGHT, channels: 3, background: p.paper } })
    .composite([{ input: Buffer.from(overlay(p)), top: 0, left: 0 }])
    // Flat colours compress very well; mozjpeg keeps the edges clean at this quality.
    .jpeg({ quality: 78, mozjpeg: true })
    .toFile(target);
  const { size } = await stat(target);
  const kb = (size / 1024).toFixed(1);
  if (size > MAX_BYTES) throw new Error(`${p.file} is ${kb} KB, over the 200 KB limit`);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${kb} KB)`);
}

await mkdir(outDir, { recursive: true });
for (const p of placeholders) await make(p);
